"""Export the fitted pipeline to JSON for in-browser inference and inline it into index.html.

Run (from ml/): .venv/bin/python export_model.py   (needs artifacts/model.pkl from train_router.py)
Writes ../model.json and replaces the block between the MODEL markers inside index.html's <script>
(inline so the page works from file:// and on any static host). Only that block is touched.
"""
import json
import pickle
from pathlib import Path

from common import ART, DATA, load_chunks

APP = Path(__file__).resolve().parent.parent
BEGIN = "// ---- MODEL (generated by ml/export_model.py; do not edit by hand) ----"
END = "// ---- END MODEL ----"
CONFLICTS = [
    {"chunks": ["canvas:poster-presentation", "page:important-dates:0"], "if_tokens": ["poster"],
     "note": "Sources disagree: Canvas lists Poster Presentation due Mon 30 Nov 2026, 23:59 HKT; the course "
             "project page says the poster link is due one day before your assigned presentation session."},
    {"chunks": ["canvas:final-report-with-video-trailer-link"], "if_tokens": [],
     "note": "Canvas shows this item as 10 points; the course project page weights the Final Report 7 and the "
             "Video Trailer 3 (of 22). The calculator uses the course page weights."},
]


def main():
    m = pickle.load((ART / "model.pkl").open("rb"))
    v, lr, r = m["router_vec"], m["lr"], m["retriever"]
    chunks = load_chunks()
    vocab = {t: int(i) for t, i in v.vocabulary_.items()}
    model = {
        "version": 1,
        "router": {"analyzer": m["router_analyzer"], "vocab": vocab, "idf": v.idf_.tolist(),
                   "classes": lr.classes_.tolist(), "coef": lr.coef_.tolist(), "intercept": lr.intercept_.tolist()},
        "retriever": {"type": m["retriever_name"], "K": m["K"]},
        "threshold": m["threshold"], "decimals": 10,
        "chunks": [{"id": c["id"], "source": c["source"], "text": c["text"]} for c in chunks],
        "weights": json.loads((DATA / "weights.json").read_text(encoding="utf-8")),
        "conflicts": CONFLICTS,
    }
    if m["retriever_name"] == "bm25":
        b = r.bm
        model["retriever"].update(k1=b.k1, b=b.b, avgdl=b.avgdl, doc_len=list(map(int, b.doc_len)),
                                  idf={k: float(x) for k, x in b.idf.items()},
                                  tf=[{k: int(n) for k, n in d.items()} for d in b.doc_freqs])
    else:
        rv = r.vec
        X = r.X.tocsr()
        model["retriever"].update(analyzer=r.name, vocab={t: int(i) for t, i in rv.vocabulary_.items()},
                                  idf=rv.idf_.tolist(),
                                  vecs=[[[int(j), float(x)] for j, x in zip(X[i].indices, X[i].data)] for i in range(X.shape[0])])
    js = json.dumps(model, ensure_ascii=False, separators=(",", ":"))
    (APP / "model.json").write_text(js, encoding="utf-8")
    safe = js.replace("<", "\\" + "u003c")  # never let "</script>" appear inside the inline block
    html = (APP / "index.html").read_text(encoding="utf-8")
    a, b = html.index(BEGIN), html.index(END)
    html = html[:a] + BEGIN + "\nconst MODEL=" + safe + ";\n" + html[b:]
    (APP / "index.html").write_text(html, encoding="utf-8")
    print(f"model.json {len(js) / 1024:.0f} KB; inlined into index.html; router {m['router_analyzer']} "
          f"vocab {len(vocab)}, retriever {m['retriever_name']}, threshold {m['threshold']:.4f}")


if __name__ == "__main__":
    main()
